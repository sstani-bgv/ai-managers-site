def msk_day():
    return time.strftime('%Y-%m-%d', time.gmtime(time.time() + 3 * 3600))  # МСК — UTC+3 круглый год


class Spend:
    """Траты ₽ за сегодня (день по Москве) в JSON-файле: лимит переживает перезапуск."""
    def __init__(self, path, cap, name):
        self.path, self.cap, self.name, self.lock = path, cap, name, threading.RLock()
        try:
            with open(path) as f:
                d = json.load(f)
            self.day, self.rub = str(d['day']), float(d['rub'])
        except Exception:  # файла ещё нет
            self.day, self.rub = '', 0.0

    def left(self):
        """Сколько ₽ осталось на сегодня. Новый день — с нуля, итог прошлого — в лог."""
        with self.lock:
            if self.day != (day := msk_day()):
                if self.day:
                    print(f'spend {self.name} {self.day} {self.rub:.1f}/{self.cap:g}', flush=True)
                self.day, self.rub = day, 0.0
            return self.cap - self.rub

    def add(self, rub, check=False):
        """Прибавить rub к тратам дня. check: лимит уже выбран — ничего не прибавлять и вернуть False."""
        with self.lock:
            left = self.left()
            if check and left <= 0:
                return False
            self.rub += rub
            with open(self.path + '.tmp', 'w') as f:
                json.dump({'day': self.day, 'rub': round(self.rub, 3)}, f)
            os.replace(self.path + '.tmp', self.path)  # временный файл + rename: файл всегда целый
            if left > 0 >= left - rub:
                print(f'spend {self.name} {self.rub:.1f}/{self.cap:g} cap hit', flush=True)
            return True


# ₽ за 1000 токенов с НДС, AI Studio, октябрь 2026 (marketing/landing/running-costs.md): вход, выход. Кеш у этих моделей по цене входа.
PRICE = {'aliceai-llm': (0.5, 1.2), 'yandexgpt-5.1': (0.8, 0.8)}
GUESS = 3.0  # ₽ за ответ, когда usage нет: с запасом


def cost(model, usage):
    """₽ за один ответ чата по usage из ответа Яндекса. Модели нет в PRICE — по самой дорогой цене таблицы (Pro 5: 1,2 ₽)."""
    try:
        p_in, p_out = PRICE.get(model.split('/')[0], (1.2, 1.2))
        return (int(usage['inputTextTokens']) * p_in + int(usage['completionTokens']) * p_out) / 1000  # числа приходят строками
    except Exception:
        return GUESS


class Demo:
    def __init__(self, env, state):
        self.key, self.folder = env['YC_API_KEY'], env['YC_FOLDER']
        self.model = env.get('YC_CHAT_MODEL', 'yandexgpt-5.1/latest')  # проверены: yandexgpt-5.1/latest, aliceai-llm/latest
        self.spend = Spend(os.path.join(state, 'spend-chat.json'), float(env.get('CHAT_RUB_DAY', 140)), 'chat')

    def _post(self, url, data, ctype=None, timeout=30):
        h = {'Authorization': 'Api-Key ' + self.key, 'x-folder-id': self.folder, 'x-data-logging-enabled': 'false'}  # просим Яндекс не сохранять запросы у себя
        if ctype:
            h['Content-Type'] = ctype
        with urllib.request.urlopen(urllib.request.Request(url, data, h), timeout=timeout) as r:
            return r.read()

    def chat(self, niche, history, model=None):
        """Ответ модели или None, если лимит ₽ на сегодня выбран."""
        # Резерв GUESS до вызова: параллельные запросы не проскочат лимит. Вызов упал — резерв остаётся (Яндекс мог и списать).
        if not self.spend.add(GUESS, check=True):
            return None
        model = model or self.model
        msgs = [{'role': 'system', 'text': prompt(niche)}, {'role': 'assistant', 'text': GREETINGS[niche]}]
        msgs += [{'role': 'user' if m['role'] == 'user' else 'assistant', 'text': m['text']} for m in history]
        body = {'modelUri': f'gpt://{self.folder}/{model}',
                'completionOptions': {'stream': False, 'temperature': 0.2, 'maxTokens': '400'}, 'messages': msgs}
        r = json.loads(self._post('https://llm.api.cloud.yandex.net/foundationModels/v1/completion', json.dumps(body).encode(), 'application/json'))['result']
        self.spend.add(cost(model, r.get('usage')) - GUESS)  # резерв → цена по usage
        return r['alternatives'][0]['message']['text'].strip()


